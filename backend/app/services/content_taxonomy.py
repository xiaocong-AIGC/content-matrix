# -*- coding: utf-8 -*-
"""内容风格分类器 —— 正则优先，确定性，可重跑，零成本。

**这里是唯一真相**：`tools/content_types.py` 只是转发，别在那边改。
后端要按类型显示和分配配额，分析脚本要按类型算效果 —— 两边判据一旦分叉，
「效果榜上说这是二选一，配额却没按二选一发」这种事没人查得出来。

**为什么是正则不是模型**：这个分类结果要用来分配配额、比较效果、判断
「哪类值得多发」。任何一个结论被质疑时，必须能把分类过程原样跑一遍给人看。
模型分类做不到这一点：同一条内容今天标 A 明天标 B，而且没人能解释为什么。
正则命中不了的残余再交模型，标 `source='llm'` 区分开。

**判据一律看标题（封面）**，不看正文。理由：
- 我们自己发的内容 94% 是「短封面。正文…」的大字报形态，封面就是那句钩子；
- 回采到的、对不上内容库的帖子只有标题；
- 正文长、噪声大，同一个钩子接什么正文都可能，拿正文分类会把「写法」
  和「题材」混成一团。

⚠ **这套类型是待验证的假设，不是定论。** 见 `analyze_types.py` 的输出：
类间差异要大过类内噪声，这套划分才站得住；站不住就退回更粗的档。

用法：
    from tools.content_types import classify, STYLE_OF
    key = classify("300万买上海地铁房实录。沙盘上全是未来规划…")
"""
import re

# ── 八类。顺序即优先级：一条标题可能同时像两类，先命中的赢 ──────────────
#
# 排序原则：**判据越硬的排越前**。「X还是Y」是结构，一眼可判；
# 「普通陈述」是兜底，什么都不像才落到它。
TYPES: list[tuple[str, str, re.Pattern]] = [
    (
        "两难选择",
        "摆出两个互斥选项，让人替他选",
        re.compile(
            r"(还是)"                          # 「南山还是龙华」
            r"|[vV][sS]|ＶＳ"                    # 「租房市中心vs买房郊区」
            r"|要么"                            # 「只剩两条路：要么继续租房…」
            r"|两条路|两个选择|A还是B"
            r"|[选买租换].{0,6}还是"
            r"|二选一|怎么选|如何选|哪个好|哪个划算"
            r"|该不该|值不值|要不要|能不能忍"
            r"|选择困难|两难|纠结"
        ),
    ),
    (
        "踩坑复盘",
        "一件已经发生的、结果不好的事",
        re.compile(
            r"实录|复盘|踩坑|翻车|后悔|教训|白跑|白等|差点"
            r"|被(骗|坑|嘲笑|跳价|忽悠|催|劝退)"
            r"|(崩溃|傻眼|愣住|哭出来|心在滴血|太难了|终放弃|放弃了)"
        ),
    ),
    (
        "开口提问",
        "直接向评论区要答案",
        re.compile(r"[?？]\s*$|[?？]|吗[，。！!]?$|呢[，。！!]?$|求.{0,4}(推荐|建议|意见)|想知道|有没有.{0,8}[推荐建议]"),
    ),
    (
        "转述别人",
        "冲突来自另一个人：中介/房东/伴侣/父母/同事",
        re.compile(
            r"中介|房东|销售|老板"
            r"|(男|女)(朋友|友)|对象|老公|老婆|伴侣"
            r"|(爸妈|父母|婆婆|丈母娘|亲戚|家里人|我妈|他妈)"
            r"|同事|朋友说|邻居"
        ),
    ),
    (
        "清单攻略",
        "教人怎么做，成体系",
        re.compile(r"指南|攻略|清单|盘点|科普|干货|必看|收藏|步骤|流程|注意事项"
        r"|避雷|避坑|绝对不能买|千万别买|\d+\s*(个|条|点|招|坑)"),
    ),
    (
        "行情通报",
        "讲市场，不讲自己",
        re.compile(r"房价|涨|跌|抄底|砸盘|成交|挂牌|均价|单价|行情|市场|倒挂|限购|政策|新政|利率"),
    ),
    (
        "数字摆事实",
        "用一个具体金额开场",
        re.compile(r"^\D{0,6}\d+\s*(万|w|W|块|元|平|年)"),
    ),
    ("普通陈述", "以上都不是", re.compile(r"")),
]

# ── 三档风格：配额和效果判决的单位 ──────────────────────────────────
#
# **这三档是 2026-09-10 用 1256 条 note 实测定下来的**（`analyze_types.py`），
# 三对两两比较的置信区间全部不含 0，折半复现两半排序一致：
#
#     二选一 0.551 [0.510,0.594]  >  日常讲述 0.495 [0.475,0.516]
#                                 >  清单行情 0.383 [0.313,0.453]
#
# ⚠ **踩坑复盘不能和两难选择合成一档。** 方案原本把它们并成「纠结对比」，
# 而实测 两难选择 0.551、踩坑复盘 0.456 —— 一好一坏平均掉，合并之后
# 和「日常讲述」的差就落进了噪声里（CI [-0.018,+0.062] 含 0）。
# 这是「凭语义相近就归类」和「按效果归类」的区别。
#
# ⚠ **这组 CI 是挑选后的 CI。** 划分是看过八类结果之后定的，所以偏乐观。
# 上线之后必须拿新数据再估一次，别把它当既成事实。
STYLE_OF: dict[str, str] = {
    "两难选择": "二选一",          # 唯一显著更好的一档
    "踩坑复盘": "日常讲述",
    "开口提问": "日常讲述",
    "转述别人": "日常讲述",
    "数字摆事实": "日常讲述",
    "普通陈述": "日常讲述",
    "清单攻略": "清单行情",        # 唯一显著更差的一档
    "行情通报": "清单行情",
}

STYLES = ("二选一", "日常讲述", "清单行情")

# ── 不该进分析的行 ────────────────────────────────────────────────
#
# ⚠ 抖音官方的推广内容会混进回采结果里（浏览 0、评论上千），而评论是主指标 ——
# 不滤掉，这 9 条就主宰全部结论。2026-09-10 实测：命中官方词的 9 条，
# 评论中位数 542，而我们自己内容的评论中位数是 8。
OFFICIAL = re.compile(
    r"创作阶梯|合集升级|创作指南|抖音精选|创作者服务|激励计划"
    r"|稀缺创作资源|欢迎加入|官方扶持|脑洞创造惊喜"
    # 「作品共获得 2210 流量激励」这类是平台给创作者的通知，不是内容
    r"|流量激励|作品共获得"
)


def is_noise(title: str, views: int) -> str:
    """这一条该不该被排除在分析之外。返回排除理由，空串 = 可用。"""
    text = (title or "").strip()
    if not text:
        return "无标题"
    if text == "私密作品":
        return "私密作品"
    if OFFICIAL.search(text):
        return "抖音官方推广内容"
    # 浏览为 0 的：要么不是我们发的，要么刚发还没数据。两种都不该参与比较。
    if not views:
        return "浏览为 0"
    return ""


# 我们自己发的大字报，回采回来的 title 是「封面。正文开头…」拼在一起的。
# 封面才是那句钩子，正文是展开 —— 拿整串分类会让正文里的词盖掉封面里的。
# 实测：「300万北京买房指南。中介说300万能买亦庄」被正文的「中介」判成
# 「转述别人」，而它明明是一条攻略。
_COVER = re.compile(r"^(.{4,24}?)[。．]")


def cover_of(title: str) -> str:
    """取封面那一句。取不到（回采到的别人的帖子多半没有这个形态）就用整串。"""
    text = (title or "").strip()
    hit = _COVER.match(text)
    return hit.group(1) if hit else text


def classify(title: str) -> str:
    """返回八类之一。判据只看封面那一句，理由见 `cover_of`。"""
    text = cover_of(title)
    if not text:
        return "普通陈述"
    # 话题标签是平台功能不是写法，先摘掉，否则 #上海买房攻略 会把一切
    # 都判成「清单攻略」—— 我们几乎每条都挂着这类标签。
    text = re.sub(r"#\S+", " ", text)
    for name, _desc, pattern in TYPES:
        if name == "普通陈述":
            continue
        if pattern.search(text):
            return name
    return "普通陈述"


def style(title: str) -> str:
    """返回三档风格之一。"""
    return STYLE_OF[classify(title)]

# ── 给界面和配额用的**两档** ──────────────────────────────────────
#
# 上面那三档里，「日常讲述 vs 清单行情」实测 CI [-0.031, +0.122] **含 0** ——
# 分不开就不该画这条线。所以对外只报两档：**二选一 / 其余**。
#
#     二选一  n= 130  块内位次 0.581  评论中位 16  p90 174
#     其余    n=1109  块内位次 0.490  评论中位  7  p90  60
#     差 +0.091，CI [+0.034, +0.148]
#
# 三档的 STYLE_OF 保留不删：清单行情现在只有 69 条，样本涨上来之后它有可能
# 分得出来。删了以后要重新发明一遍。
TIER_BEST = "二选一"
TIER_REST = "其余"
TIERS = (TIER_BEST, TIER_REST)


def tier(title: str) -> str:
    """界面和配额用这个。返回「二选一」或「其余」。"""
    return TIER_BEST if classify(title) == "两难选择" else TIER_REST
